test("regexSourceToGlob converts simple anchored regex back to glob", () => {
  assert.equal(regexSourceToGlob("^git .*$"), "git *");
  assert.equal(regexSourceToGlob("^pnpm .*$"), "pnpm *");
  assert.equal(regexSourceToGlob("^rm -rf .*$"), "rm -rf *");
});

test("regexSourceToGlob converts .+ to *", () => {
  assert.equal(regexSourceToGlob("^npm .+$"), "npm *");
});

test("regexSourceToGlob unescapes common chars", () => {
  assert.equal(regexSourceToGlob("^git\\.status$"), "git.status");
});

test("regexSourceToGlob flags complex patterns with regex marker", () => {
  const result = regexSourceToGlob("^(git|svn) .*$");
  assert.ok(result.includes("# regex:"), "Should contain regex comment marker");
  assert.ok(result.includes("^(git|svn) .*$"), "Should include original source");
});

test("regexSourceToGlob flags character classes with regex marker", () => {
  const result = regexSourceToGlob("^[a-z]+ .*$");
  assert.ok(result.includes("# regex:"), "Should contain regex comment marker");
});

test("regexSourceToGlob flags look-ahead patterns with regex marker", () => {
  const result = regexSourceToGlob("^(?!rm).*$");
  assert.ok(result.includes("# regex:"), "Should contain regex comment marker");
});

