const PROJECT_ROOT = resolve(__dirname, "..", "..");
const CLI = resolve(PROJECT_ROOT, "src", "cli.ts");
const TSX = resolve(PROJECT_ROOT, "node_modules", ".bin", "tsx");

function runScan(
  cwd: string,
  args: string[] = []
): { stdout: string; stderr: string; exitCode: number } {
  const result = spawnSync(TSX, [CLI, "scan", ...args], {
    cwd,
    encoding: "utf8",
    env: { ...process.env, NODE_NO_WARNINGS: "1" }
  });
  return { stdout: result.stdout, stderr: result.stderr, exitCode: result.status ?? 1 };
}

function makeTmpDir(): string {
  return mkdtempSync(join(tmpdir(), "agentctl-scan-"));
}

function writeClaude(root: string, allow: string[], deny: string[]): void {
  const settings = {
    $schema: "https://json.schemastore.org/claude-code-settings.json",
    permissions: {
      allow: ["Edit", "Write", ...allow.map((p) => `Bash(${p})`)],
      deny: deny.map((p) => `Bash(${p})`)
    }
  };
  mkdirSync(join(root, ".claude"), { recursive: true });
  writeFileSync(join(root, ".claude", "settings.json"), JSON.stringify(settings, null, 2), "utf8");
}

function writeClaudeRaw(root: string, content: string): void {
  mkdirSync(join(root, ".claude"), { recursive: true });
  writeFileSync(join(root, ".claude", "settings.json"), content, "utf8");
}

function writeCodexToml(root: string, policy: string): void {
  const toml = `approval_policy = "${policy}"\nsandbox_mode = "workspace-write"\n`;
  mkdirSync(join(root, ".codex"), { recursive: true });
  writeFileSync(join(root, ".codex", "config.toml"), toml, "utf8");
}

function writeCodexHook(root: string, allow: string[], deny: string[]): void {
  const allowRegex = allow.map((g) => `^${g.replace(/\*/g, ".*")}$`);
  const denyRegex = deny.map((g) => `^${g.replace(/\*/g, ".*")}$`);
  const hook = `#!/usr/bin/env python3
DENY_PATTERNS = ${JSON.stringify(denyRegex, null, 2)}

ALLOW_PATTERNS = ${JSON.stringify(allowRegex, null, 2)}

def main():
    pass
`;
  mkdirSync(join(root, ".codex", "hooks"), { recursive: true });
  writeFileSync(join(root, ".codex", "hooks", "permission-policy.py"), hook, "utf8");
}

function writeCodexJson(root: string, policy: string, allow: string[], deny: string[]): void {
  const config = {
    approval_policy: policy,
    shell: { allow, deny }
  };
  writeFileSync(join(root, "codex.json"), JSON.stringify(config, null, 2), "utf8");
}

function writeKiro(
  root: string,
  rules: Array<{ capability: string; effect: string; match?: string[] }>
): void {
  const { stringify } = require("yaml");
  const content = stringify({ rules });
  mkdirSync(join(root, ".kiro", "settings"), { recursive: true });
  writeFileSync(join(root, ".kiro", "settings", "permissions.yaml"), content, "utf8");
}

function writeOpenCode(
  root: string,
  permission: { edit?: string; write?: string; bash?: Record<string, string> }
): void {
  const config = { permission };
  mkdirSync(join(root, ".opencode"), { recursive: true });
  writeFileSync(join(root, ".opencode", "opencode.json"), JSON.stringify(config, null, 2), "utf8");
}

function writeCursorRule(
  root: string,
  opts: { shell?: string; edit?: string; write?: string; deny?: string[]; allow?: string[] }
): void {
  const lines: string[] = [];
  lines.push("---");
  lines.push('description: "Shell and filesystem permissions enforced by agentctl"');
  lines.push("alwaysApply: true");
  lines.push("---");
  lines.push("");
  lines.push("# Permissions Policy");
  lines.push("");
  lines.push("This rule is generated by agentctl. Do not edit directly.");
  lines.push("");
  lines.push("## Filesystem");
  lines.push("");
  lines.push(`- File editing: ${opts.edit ?? "allow"}`);
  lines.push(`- File creation/write: ${opts.write ?? "allow"}`);
  lines.push("");
  lines.push("## Shell Commands");
  lines.push("");
  lines.push(`Default policy: ${opts.shell ?? "ask"}`);
  lines.push("");
  if (opts.deny && opts.deny.length > 0) {
    lines.push("### Denied (never run these)");
    lines.push("");
    for (const p of opts.deny) lines.push(`- \`${p}\``);
    lines.push("");
  }
  if (opts.allow && opts.allow.length > 0) {
    lines.push("### Allowed (safe to run without asking)");
    lines.push("");
    for (const p of opts.allow) lines.push(`- \`${p}\``);
    lines.push("");
  }
  const dir = join(root, ".cursor", "rules", "agentctl-permissions");
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "RULE.md"), lines.join("\n"), "utf8");
}

